// lib/model.ts — Fitted token launch pricing model & farm plan generator for token-radar-01
// Runtime fitted launch pricing: derives base category multiples dynamically from snapshot live-token protocols.

export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

export interface ModelConstants {
  global_base_multiple: number;
  category_multiples: Record<string, number>;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
}

export const MODEL_VERSION = 'radar-2-fitted';

export interface FarmStep {
  text: string;
  cost: string;
  time: string;
}

